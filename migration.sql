-- Browser only needs to READ public cards/tasks/leaderboard data.
drop policy if exists upgrades_public_read on public.upgrades;
create policy upgrades_public_read on public.upgrades for select to anon, authenticated using (true);
drop policy if exists tasks_public_read on public.tasks;
create policy tasks_public_read on public.tasks for select to anon, authenticated using (active = true);
drop policy if exists users_public_leaderboard on public.users;
create policy users_public_leaderboard on public.users for select to anon, authenticated using (true);

