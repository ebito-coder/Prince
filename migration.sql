alter table public.users add column if not exists airdrop_points bigint not null default 0;
alter table public.users add column if not exists tap_power integer not null default 1;
alter table public.users add column if not exists profit_hour bigint not null default 0;
alter table public.users add column if not exists last_tap_at timestamptz;
alter table public.users add column if not exists last_daily_combo date;
alter table public.users add column if not exists daily_combo_claimed boolean not null default false;
alter table public.upgrades add column if not exists category text not null default 'General';
alter table public.upgrades add column if not exists icon text default '🃏';

create table if not exists public.game_scores(
 id bigint generated by default as identity primary key,
 telegram_id bigint not null,
 score integer not null,
 reward bigint not null default 0,
 created_at timestamptz not null default now()
);
create table if not exists public.daily_combos(
 combo_date date primary key,
 card_1 bigint not null references public.upgrades(id) on delete cascade,
 card_2 bigint not null references public.upgrades(id) on delete cascade,
 card_3 bigint not null references public.upgrades(id) on delete cascade,
 reward bigint not null default 5000000
);
create table if not exists public.transactions(
 id bigint generated by default as identity primary key,
 telegram_id bigint not null,
 type text not null,
 amount bigint not null,
 reference_id text,
 metadata jsonb,
 created_at timestamptz not null default now()
);
create table if not exists public.admin_actions(
 id bigint generated by default as identity primary key,
 admin_telegram_id bigint not null,
 action text not null,
 target_telegram_id bigint,
 metadata jsonb,
 created_at timestamptz not null default now()
);

create index if not exists game_scores_user_idx on public.game_scores(telegram_id, created_at desc);
create index if not exists transactions_user_idx on public.transactions(telegram_id, created_at desc);
create index if not exists admin_actions_target_idx on public.admin_actions(target_telegram_id, created_at desc);

alter table public.users enable row level security;
